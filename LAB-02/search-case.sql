DECLARE
I NUMBER;
BEGIN
I:=&I;
CASE 
WHEN I BETWEEN 1 AND 5 THEN 
DBMS_OUTPUT.PUT_LINE('Week day');
WHEN I=6 THEN
DBMS_OUTPUT.PUT_LINE('Saturday');
ELSE
DBMS_OUTPUT.PUT_LINE('Friday');
END CASE;
END;