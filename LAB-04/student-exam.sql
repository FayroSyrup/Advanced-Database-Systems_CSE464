DECLARE
V_ID STUDENT_EXAM.ID %Type;
V_NOA STUDENT_EXAM.NUMBER_OF_ATTENDANCE %TYPE;
V_EN STUDENT_EXAM.EXAM_NUMBER %TYPE;
CURSOR C_s IS SELECT * FROM STUDENT_EXAM;
BEGIN
OPEN C_s;
Loop
Fetch C_s Into V_Id, V_NOA, V_EN;
Exit when C_s%Notfound;
IF V_EN < 40 THEN
IF V_NOA > 10 THEN
UPDATE STUDENT_EXAM
SET EXAM_NUMBER = EXAM_NUMBER + 4
Where ID = V_ID;
DBMS_OUTPUT.PUT_LINE('Bonus +4 added for ID: ' || V_ID);
ELSIF V_NOA BETWEEN 6 AND 10 THEN
UPDATE STUDENT_EXAM
SET EXAM_NUMBER = EXAM_NUMBER + 3
Where ID = V_ID;
DBMS_OUTPUT.PUT_LINE('Bonus +3 added for ID: ' || V_ID);
ELSIF V_NOA >= 3 AND V_NOA <= 5 THEN
UPDATE STUDENT_EXAM
SET EXAM_NUMBER = EXAM_NUMBER + 2
Where ID = V_ID;
DBMS_OUTPUT.PUT_LINE('Bonus +2 added for ID: ' || V_ID);
ELSE
DBMS_OUTPUT.PUT_LINE('No bonus applicable for ID: ' || V_ID);
END IF;
Else
DBMS_OUTPUT.PUT_LINE('Already Passed. No update for ID: ' || V_ID);
END if;
END Loop;
Close C_s;
END;